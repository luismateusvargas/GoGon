// scripts/catalog/build-relay-userscript.mjs - CAT-TASK-010 / AC-CAT-014 (catalog-sync-v1 1.3.0)
// Builds reconciliation/scrappers/gogon_guide_relay.user.js from the same modules the server tests
// exercise (catalog/contracts/guide.js, catalog/contracts/classify.js, catalog/guideParsers.js,
// catalog/relayClient.js), plus the userscript glue below.
//   node scripts/catalog/build-relay-userscript.mjs          write the userscript
//   node scripts/catalog/build-relay-userscript.mjs --check  exit 1 when the committed file is stale
//
// The userscript replaces the supplied scrapers' @grant none with GM_xmlhttpRequest, GM_getValue,
// GM_setValue, and GM_registerMenuCommand, and may only connect to 127.0.0.1 (the owner's SSH tunnel
// to the GoGon control plane). The relay token lives in Tampermonkey storage only: set it in the
// script's Storage tab. It is never shown, prompted for, or passed to the guide page.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const OUTPUT = path.join(ROOT, 'reconciliation', 'scrappers', 'gogon_guide_relay.user.js');
export const MODULES = ['catalog/contracts/guide.js', 'catalog/contracts/classify.js', 'catalog/guideParsers.js', 'catalog/relayClient.js'];
export const VERSION = '1.0.2';

const HEADER = `// ==UserScript==
// @name         GoGon Guide Relay
// @namespace    gogon
// @version      ${VERSION}
// @description  Reads the guide pages GoGon asks for (one at a time) and sends parsed records to your GoGon control plane over 127.0.0.1.
// @match        https://guide.fallensword.com/*
// @grant        GM_xmlhttpRequest
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_registerMenuCommand
// @connect      127.0.0.1
// @run-at       document-idle
// @noframes
// ==/UserScript==
// GENERATED by scripts/catalog/build-relay-userscript.mjs from ${MODULES.join(', ')}. Do not edit.
// catalog-sync-v1 CAT-TASK-010. Setup: in the GoGon Catalog tab enable a guide_discovery job and
// issue a relay token; in Tampermonkey open this script's Storage tab and set "gogonRelayToken" to
// it (and "gogonRelayPort" if the control plane is not on 8787); open the SSH tunnel; open any
// guide.fallensword.com page and press Start.
`;

const GLUE = `
    // --- relay glue (userscript only) -------------------------------------------------------------
    const PORT_KEY = 'gogonRelayPort';
    const TOKEN_KEY = 'gogonRelayToken';
    const RUN_KEY = 'gogonRelayRunning';
    const LOCK_KEY = 'gogonRelayLock';
    const RESULTS_KEY = 'gogonRelayResults';
    const IDLE_POLL_MS = 5 * 60 * 1000;
    const ERROR_POLL_MS = 60 * 1000;
    const LOCK_STALE_MS = 90 * 1000;
    const STATUS_TEXT = {
        disabled: 'the guide job is not enabled in the Catalog tab.',
        paused: 'the guide job is paused.',
        idle: 'nothing is due; checking again later.',
        busy: 'another browser is running the relay.',
    };
    const tabId = Math.random().toString(36).slice(2);
    let stopped = true;
    let heartbeat = null;

    const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
    const port = () => {
        const p = Number(GM_getValue(PORT_KEY, 8787));
        return Number.isInteger(p) && p > 0 && p < 65536 ? p : 8787;
    };

    const panel = document.createElement('div');
    panel.style.cssText = 'position:fixed;bottom:8px;right:8px;z-index:2147483647;max-width:340px;padding:8px 10px;font:12px/1.4 system-ui,sans-serif;background:#1c2029;color:#e7eaf0;border:1px solid #2d3340;border-radius:8px';
    const statusLine = document.createElement('div');
    const toggle = document.createElement('button');
    toggle.type = 'button';
    toggle.style.cssText = 'margin-top:6px';
    panel.append(statusLine, toggle);
    document.body.append(panel);
    const show = text => { statusLine.textContent = 'GoGon relay: ' + text; };
    const refreshButton = () => { toggle.textContent = stopped ? 'Start' : 'Stop'; };

    function relayRequest(method, route, body, token) {
        return new Promise((resolve, reject) => {
            GM_xmlhttpRequest({
                method,
                url: 'http://127.0.0.1:' + port() + route,
                headers: { Authorization: 'Bearer ' + token, 'Content-Type': 'application/json' },
                data: body ? JSON.stringify(body) : undefined,
                timeout: 30000,
                anonymous: true,
                onload: r => { let json = null; try { json = JSON.parse(r.responseText); } catch { /* not JSON */ } resolve({ status: r.status, json }); },
                onerror: () => reject(new Error('unreachable')),
                ontimeout: () => reject(new Error('timeout')),
            });
        });
    }

    // Guide pages are read same-origin by this browser, with its own validated session.
    async function fetchPage(url) {
        const res = await fetch(url, { credentials: 'same-origin', redirect: 'follow' });
        return { status: res.status, contentType: res.headers.get('content-type') || '', cfMitigated: res.headers.get('cf-mitigated'), body: await res.text() };
    }
    const parseHtml = html => new DOMParser().parseFromString(html, 'text/html');

    // Results read for a lease are kept in Tampermonkey storage until GoGon settles them, so a failed
    // submission is resent as read, never read again (relayCycle in catalog/relayClient.js).
    const saved = {
        get: () => GM_getValue(RESULTS_KEY, null),
        set: value => GM_setValue(RESULTS_KEY, value),
    };

    async function cycle() {
        const token = GM_getValue(TOKEN_KEY, '');
        if (!token) { show('no relay token. In Tampermonkey, open this script\\'s Storage tab and set gogonRelayToken.'); return stop(); }
        const out = await relayCycle({
            getLease: () => relayRequest('GET', '/relay/guide/lease', null, token),
            postResults: (leaseId, body) => relayRequest('POST', '/relay/guide/leases/' + leaseId, body, token),
            saved, fetchPage, parseHtml, sleep, stopped: () => stopped,
            onRead: lease => show('reading ' + lease.work.length + ' ' + lease.kind + (lease.work[0].type === 'index' ? ' index' : ' detail') + ' page(s)...'),
        });
        const keep = out.kept ? ' The results are kept and will be sent again, not read again.' : '';
        if (out.step === 'unreachable') { show('GoGon is not reachable on 127.0.0.1:' + port() + ' (is the SSH tunnel open?).' + keep); return sleep(ERROR_POLL_MS); }
        if (out.step === 'unauthorized') { show('the relay token is missing, expired, or revoked.'); return stop(); }
        if (out.step === 'http') { show('GoGon answered HTTP ' + out.status + '.' + keep); return sleep(ERROR_POLL_MS); }
        if (out.step === 'no_lease') { show(STATUS_TEXT[out.status] || String(out.status)); return sleep(IDLE_POLL_MS); }
        if (out.step === 'refused') { show('GoGon refused the results (HTTP ' + out.status + '); asking for new work.'); return sleep(ERROR_POLL_MS); }
        if (out.challenge) { show('Cloudflare asked for a check. Complete it yourself on a guide page, then press Start.'); return stop(); }
        show((out.resent ? 'resent ' : 'sent ') + out.results + ' result(s)' + (out.sweepComplete ? '; sweep complete' : '') + '.');
        return sleep(out.minDelayMs);
    }

    function otherTabRunning() {
        const lock = GM_getValue(LOCK_KEY, null);
        return Boolean(lock && lock.tab !== tabId && Date.now() - lock.at < LOCK_STALE_MS);
    }

    function start() {
        if (!stopped) return;
        if (otherTabRunning()) { show('already running in another tab.'); return; }
        stopped = false;
        GM_setValue(RUN_KEY, true);
        GM_setValue(LOCK_KEY, { tab: tabId, at: Date.now() });
        heartbeat = setInterval(() => GM_setValue(LOCK_KEY, { tab: tabId, at: Date.now() }), 30 * 1000);
        refreshButton();
        (async () => {
            while (!stopped) {
                try { await cycle(); } catch { show('unexpected error; retrying in a minute.'); await sleep(ERROR_POLL_MS); }
            }
        })();
    }

    function stop() {
        stopped = true;
        GM_setValue(RUN_KEY, false);
        clearInterval(heartbeat);
        const lock = GM_getValue(LOCK_KEY, null);
        if (lock && lock.tab === tabId) GM_setValue(LOCK_KEY, null);
        refreshButton();
    }

    toggle.addEventListener('click', () => (stopped ? start() : stop()));
    GM_registerMenuCommand('GoGon relay: start', start);
    GM_registerMenuCommand('GoGon relay: stop', stop);
    refreshButton();
    show(GM_getValue(TOKEN_KEY, '') ? 'stopped.' : 'set gogonRelayToken in this script\\'s Storage tab.');
    if (GM_getValue(RUN_KEY, false)) start();
`;

/** Module source with imports dropped and export keywords removed. */
function inline(rel) {
    const src = fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');
    const body = src.split('\n').filter(line => !/^import\s/.test(line)).join('\n').replace(/^export\s+/gm, '');
    return `    // --- inlined from ${rel} ---\n${body.trim().split('\n').map(l => (l ? `    ${l}` : '')).join('\n')}\n`;
}

export function buildRelayUserscript() {
    return `${HEADER}\n(function () {\n    'use strict';\n\n${MODULES.map(inline).join('\n')}${GLUE}})();\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const built = buildRelayUserscript();
    if (process.argv.includes('--check')) {
        const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : '';
        if (current !== built) {
            console.error(`[relay] ${path.relative(ROOT, OUTPUT)} is out of date; run node scripts/catalog/build-relay-userscript.mjs`);
            process.exitCode = 1;
        } else {
            console.log('[relay] userscript is up to date.');
        }
    } else {
        fs.writeFileSync(OUTPUT, built);
        console.log(`[relay] wrote ${path.relative(ROOT, OUTPUT)}`);
    }
}
